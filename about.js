function setupAboutSlider() {

    const slider =
        document.getElementById(
            "aboutSlider"
        );

    if (!slider) {
        return;
    }

    const slides =
        document.querySelectorAll(
            ".about-slide"
        );

    const dots =
        document.querySelectorAll(
            ".about-slider-dots .dot"
        );

    const prevBtn =
        document.getElementById(
            "aboutPrevBtn"
        );

    const nextBtn =
        document.getElementById(
            "aboutNextBtn"
        );

    let currentIndex = 0;

    let autoTimer =
        setInterval(
            goToNext,
            3000
        );


    function goToSlide(index) {

        slides.forEach(
            function (slide, i) {

                slide.classList.toggle(
                    "active",
                    i === index
                );

            }
        );

        if (dots.length) {

            dots.forEach(
                function (dot, i) {

                    dot.classList.toggle(
                        "active",
                        i === index
                    );

                }
            );

        }

        currentIndex = index;

    }


    function goToNext() {

        const nextIndex =
            (currentIndex + 1) %
            slides.length;

        goToSlide(
            nextIndex
        );

    }


    function goToPrev() {

        const prevIndex =
            (currentIndex - 1 +
                slides.length) %
            slides.length;

        goToSlide(
            prevIndex
        );

    }


    if (prevBtn) {

        prevBtn.addEventListener(
            "click",
            function () {

                goToPrev();

                resetAuto();

            }
        );

    }


    if (nextBtn) {

        nextBtn.addEventListener(
            "click",
            function () {

                goToNext();

                resetAuto();

            }
        );

    }


    dots.forEach(
        function (dot, index) {

            dot.addEventListener(
                "click",
                function () {

                    goToSlide(
                        index
                    );

                    resetAuto();

                }
            );

        }
    );


    function resetAuto() {

        clearInterval(
            autoTimer
        );

        autoTimer =
            setInterval(
                goToNext,
                3000
            );

    }


    // تفعيل النقطة الأولى

    goToSlide(0);

}



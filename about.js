let toastTimer = null;


function showToast(
    title,
    message
) {

    createToastIfMissing();


    const toast =
        document.getElementById(
            "toastMessage"
        );


    const toastTitle =
        document.getElementById(
            "toastTitle"
        );


    const toastText =
        document.getElementById(
            "toastText"
        );


    if (
        !toast ||
        !toastTitle ||
        !toastText
    ) {

        return;

    }


    toastTitle.textContent =
        title;


    toastText.textContent =
        message;


    toast.classList.remove(
        "show"
    );


    // إعادة تشغيل الحركة

    void toast.offsetWidth;


    toast.classList.add(
        "show"
    );


    if (toastTimer) {

        clearTimeout(
            toastTimer
        );

    }


    toastTimer =
        setTimeout(
            function() {

                toast.classList.remove(
                    "show"
                );

            },
            3500
        );

}



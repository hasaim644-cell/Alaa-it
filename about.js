// =====================================
// إعداد أحداث خيارات الحجز
// =====================================

function setupBookingOptionEvents() {

    const options =
        document.querySelectorAll(
            ".booking-option"
        );


    options.forEach(function(option) {

        const input =
            option.querySelector(
                "input[type='radio']"
            );


        if (!input) {
            return;
        }


        // =================================
        // عند الضغط على البطاقة
        // =================================

        option.addEventListener(
            "click",
            function(event) {

                // إذا ضغط على input نفسه
                // نترك المتصفح يتعامل معه

                input.checked = true;


                // إزالة selected من باقي البطاقات

                const group =
                    option.parentElement
                        .querySelectorAll(
                            ".booking-option"
                        );


                group.forEach(function(item) {

                    item.classList.remove(
                        "selected"
                    );

                });


                // إضافة selected للبطاقة المختارة

                option.classList.add(
                    "selected"
                );

            }
        );


        // =================================
        // عند تغيير radio
        // =================================

        input.addEventListener(
            "change",
            function() {

                const group =
                    option.parentElement
                        .querySelectorAll(
                            ".booking-option"
                        );


                group.forEach(function(item) {

                    item.classList.remove(
                        "selected"
                    );

                });


                option.classList.add(
                    "selected"
                );

            }
        );

    });

}


